CREATE TABLE IF NOT EXISTS ledger_accounts (
  origin TEXT NOT NULL DEFAULT 'legacy_demo' CHECK(origin='legacy_demo'),
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY, code TEXT NOT NULL, name TEXT NOT NULL, currency TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN ('asset','liability','equity','income','expense','off-balance')),
  owner_id TEXT, account_id TEXT,
  UNIQUE(owner_id,account_id), FOREIGN KEY(owner_id,account_id) REFERENCES bank_accounts(owner_id,id)
);
CREATE TABLE IF NOT EXISTS journal_batches (
  origin TEXT NOT NULL DEFAULT 'legacy_demo' CHECK(origin='legacy_demo'),
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY, kind TEXT NOT NULL CHECK(kind IN ('opening','balance-change')),
  source TEXT NOT NULL, request_id TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','posted')),
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);
CREATE TABLE IF NOT EXISTS journal_entries (
  origin TEXT NOT NULL DEFAULT 'legacy_demo' CHECK(origin='legacy_demo'),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES journal_batches(id),
  ledger_account_id TEXT NOT NULL REFERENCES ledger_accounts(id), currency TEXT NOT NULL,
  debit_cents BIGINT NOT NULL CHECK(debit_cents BETWEEN 0 AND 9007199254740991),
  credit_cents BIGINT NOT NULL CHECK(credit_cents BETWEEN 0 AND 9007199254740991),
  CHECK((debit_cents > 0 AND credit_cents = 0) OR (credit_cents > 0 AND debit_cents = 0))
);
CREATE INDEX IF NOT EXISTS idx_journal_entries_account ON journal_entries(ledger_account_id,batch_id);
CREATE TABLE IF NOT EXISTS balance_changes (
  origin TEXT NOT NULL DEFAULT 'legacy_demo' CHECK(origin='legacy_demo'),
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES journal_batches(id),
  owner_id TEXT NOT NULL, account_id TEXT NOT NULL, before_cents BIGINT NOT NULL, after_cents BIGINT NOT NULL,
  FOREIGN KEY(owner_id,account_id) REFERENCES bank_accounts(owner_id,id), UNIQUE(batch_id,owner_id,account_id)
);

CREATE OR REPLACE FUNCTION bank_reject_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable financial record: %', TG_TABLE_NAME USING ERRCODE='23514'; END;
$$;
CREATE OR REPLACE FUNCTION bank_guard_entry() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE batch_state TEXT; account_currency TEXT;
BEGIN
 SELECT state INTO batch_state FROM journal_batches WHERE id=NEW.batch_id FOR UPDATE;
 IF batch_state IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'posted journal is immutable' USING ERRCODE='23514'; END IF;
 SELECT currency INTO account_currency FROM ledger_accounts WHERE id=NEW.ledger_account_id;
 IF account_currency IS DISTINCT FROM NEW.currency THEN RAISE EXCEPTION 'journal currency mismatch' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION bank_guard_batch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  IF NEW.state<>'draft' THEN RAISE EXCEPTION 'journal must start as draft' USING ERRCODE='23514'; END IF;
 ELSE
  IF OLD.state='posted' THEN RAISE EXCEPTION 'posted journal is immutable' USING ERRCODE='23514'; END IF;
  IF NEW.state='posted' THEN
   IF (SELECT COUNT(*) FROM journal_entries WHERE batch_id=NEW.id)<2 THEN RAISE EXCEPTION 'journal requires two entries' USING ERRCODE='23514'; END IF;
   IF EXISTS(SELECT currency FROM journal_entries WHERE batch_id=NEW.id GROUP BY currency HAVING SUM(debit_cents)<>SUM(credit_cents)) THEN RAISE EXCEPTION 'journal is unbalanced' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION bank_require_posted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM journal_batches WHERE id=NEW.id AND state<>'posted') THEN RAISE EXCEPTION 'draft journal cannot be committed' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END;
$$;
CREATE OR REPLACE FUNCTION bank_guard_balance_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE batch_state TEXT;
BEGIN
 SELECT state INTO batch_state FROM journal_batches WHERE id=NEW.batch_id FOR UPDATE;
 IF batch_state IS DISTINCT FROM 'draft' THEN RAISE EXCEPTION 'posted journal is immutable' USING ERRCODE='23514'; END IF;
 IF NEW.before_cents NOT BETWEEN 0 AND 9007199254740991 OR NEW.after_cents NOT BETWEEN 0 AND 9007199254740991 THEN RAISE EXCEPTION 'invalid balance change amount' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION bank_guard_account_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.owner_id,NEW.id,NEW.currency,NEW.account_no) IS DISTINCT FROM (OLD.owner_id,OLD.id,OLD.currency,OLD.account_no) THEN RAISE EXCEPTION 'account identity is immutable' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION bank_guard_transaction_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.owner_id,NEW.id,NEW.account_id,NEW.direction,NEW.amount_cents,NEW.signed_amount_cents,NEW.created_at,NEW.provenance) IS DISTINCT FROM (OLD.owner_id,OLD.id,OLD.account_id,OLD.direction,OLD.amount_cents,OLD.signed_amount_cents,OLD.created_at,OLD.provenance) THEN RAISE EXCEPTION 'transaction financial identity is immutable' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION bank_require_account_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE owner_key TEXT; account_key TEXT; actual_balance BIGINT; journal_balance NUMERIC;
BEGIN
 IF TG_TABLE_NAME='bank_accounts' THEN owner_key:=NEW.owner_id; account_key:=NEW.id;
 ELSE SELECT owner_id,account_id INTO owner_key,account_key FROM ledger_accounts WHERE id=NEW.ledger_account_id;
 END IF;
 IF owner_key IS NULL OR account_key IS NULL THEN RETURN NULL; END IF;
 SELECT balance_cents INTO actual_balance FROM bank_accounts WHERE owner_id=owner_key AND id=account_key;
 SELECT COALESCE(SUM(e.credit_cents-e.debit_cents),0) INTO journal_balance FROM ledger_accounts l LEFT JOIN journal_entries e ON e.ledger_account_id=l.id WHERE l.owner_id=owner_key AND l.account_id=account_key;
 IF actual_balance IS DISTINCT FROM journal_balance THEN RAISE EXCEPTION 'account balance does not equal journal balance' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END;
$$;
