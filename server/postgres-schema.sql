CREATE TABLE IF NOT EXISTS bank_schema_migrations (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  version BIGINT PRIMARY KEY, applied_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
