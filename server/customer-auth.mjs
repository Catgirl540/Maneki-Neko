import { randomBytes, randomUUID, createHash } from 'node:crypto'

/** Bearer tokens are persisted only as hashes; the database is authoritative for revocation. */
export async function createCustomerAuth(db, { lifetimeMs = 12 * 60 * 60 * 1000, now = Date.now } = {}) {
  if (!Number.isSafeInteger(lifetimeMs) || lifetimeMs < 1) throw new Error('Invalid customer session lifetime')
  if (process.env.BANK_AUTO_MIGRATE !== 'false') await db.exec(`CREATE TABLE IF NOT EXISTS customer_sessions (
    id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, phone TEXT NOT NULL,
    device TEXT NOT NULL, created_at TEXT NOT NULL, expires_at BIGINT NOT NULL, ended_at TEXT);
    CREATE INDEX IF NOT EXISTS customer_sessions_owner ON customer_sessions(owner_id, created_at);
    CREATE TABLE IF NOT EXISTS customer_auth_audit (
    id TEXT PRIMARY KEY, seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    owner_id TEXT, action TEXT NOT NULL, created_at TEXT NOT NULL, level TEXT NOT NULL);
    ALTER TABLE customer_auth_audit ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE;
    ALTER TABLE customer_sessions ADD COLUMN IF NOT EXISTS ip TEXT;
    ALTER TABLE customer_auth_audit ADD COLUMN IF NOT EXISTS ip TEXT;
    ALTER TABLE customer_auth_audit ADD COLUMN IF NOT EXISTS device TEXT;
    CREATE INDEX IF NOT EXISTS customer_auth_audit_owner ON customer_auth_audit(owner_id, created_at, seq);`)
  const stamp = () => new Date(now()).toISOString()
  const LOOPBACK = new Set(['127.0.0.1', '::1', '::ffff:127.0.0.1'])
  /**
   * 记录发起请求的客户端地址。
   *
   * 只有本机反向代理才允许用 `x-real-ip` 覆盖：直连时该头可被客户端伪造，
   * 记录一个伪造地址比记录「未知」更糟。IPv4 映射地址统一去掉前缀。
   */
  function clientIp(req) {
    const peer = String(req?.socket?.remoteAddress ?? '')
    const raw = LOOPBACK.has(peer) ? String(req?.headers?.['x-real-ip'] ?? peer) : peer
    return raw.replace(/^::ffff:/, '').slice(0, 64)
  }
  /** 地址的可读文本：本机/内网直说，公网给 IP，取不到才写未知。 */
  function locationText(ip) {
    const value = String(ip ?? '').trim()
    if (!value) return '位置未知'
    if (LOOPBACK.has(value) || /^(10\.|192\.168\.|169\.254\.)/.test(value)) return '本机网络'
    if (/^172\.(1[6-9]|2\d|3[01])\./.test(value)) return '本机网络'
    if (/^f[cd]/i.test(value)) return '本机网络'
    if (/^[0-9.]+$/.test(value)) return 'IP ' + value
    return 'IPv6 网络'
  }
  /** 设备名：平台 + 浏览器，识别不出才写未知。 */
  function deviceLabel(ua) {
    const text = String(ua ?? '')
    if (!text) return '未知设备'
    const client = /okhttp|Dalvik/i.test(text) ? '招财猫 App'
      : /MicroMessenger/i.test(text) ? '微信内置浏览器'
      : /Edg\//i.test(text) ? 'Edge'
      : /Firefox\//i.test(text) ? 'Firefox'
      : /CriOS\//i.test(text) ? 'Chrome'
      : /Chrome\//i.test(text) ? 'Chrome'
      : /Safari\//i.test(text) ? 'Safari'
      : '浏览器'
    const platform = /Android/i.test(text) ? 'Android'
      : /iPhone|iPad|iPod/i.test(text) ? 'iOS'
      : /Mac OS X|Macintosh/i.test(text) ? 'macOS'
      : /Windows/i.test(text) ? 'Windows'
      : /Linux/i.test(text) ? 'Linux'
      : ''
    if (!platform) return client === '浏览器' ? '未知设备' : client
    return platform + ' · ' + client
  }
  const audit = async (owner, action, level = 'info', meta = {}) => db.prepare('INSERT INTO customer_auth_audit (id, owner_id, action, created_at, level, ip, device) VALUES (?, ?, ?, ?, ?, ?, ?)').run(randomUUID(), owner, action, stamp(), level, meta.ip ?? null, meta.device ?? null)
  const key = req => /^Bearer ([A-Za-z0-9_-]{43})$/.exec(req?.headers?.authorization ?? '')?.[1]
  const tokenHash = token => createHash('sha256').update(token).digest('hex')
  async function end(id, ownerId, action, meta = {}) {
    // Conditional update makes repeated logout / expiry safe across server processes.
    const result = await db.prepare('UPDATE customer_sessions SET ended_at = ? WHERE id = ? AND ended_at IS NULL').run(stamp(), id)
    if (Number(result.changes ?? result.rowCount ?? 0) > 0) await audit(ownerId, action, 'info', meta)
  }
  async function current(req) {
    const token = key(req)
    if (!token) return undefined
    const row = await db.prepare('SELECT * FROM customer_sessions WHERE id = ? AND ended_at IS NULL').get(tokenHash(token))
    if (!row) return undefined
    if (Number(row.expires_at) <= now()) {
      await end(row.id, row.owner_id, '会话过期')
      return undefined
    }
    return { id: row.id, ownerId: row.owner_id, phone: row.phone, expiresAt: Number(row.expires_at) }
  }
  function requireSession(entry) {
    if (!entry) throw Object.assign(new Error('请重新登录'), { status: 401, code: 'UNAUTHORIZED' })
    return entry
  }
  return {
    async resolve(req, route) {
      if (route === 'login' || route === 'register') return null
      const entry = await current(req)
      if (route === 'smsCode' || route === 'verifyIdentity') return entry?.phone ?? null
      return requireSession(entry).phone
    },
    async identity(req) { return { id: requireSession(await current(req)).ownerId } },
    async issue(user, req) {
      const token = randomBytes(32).toString('base64url'), id = tokenHash(token)
      // Classify, never persist arbitrary headers that could contain secrets.
      const device = deviceLabel(req?.headers?.['user-agent']), ip = clientIp(req)
      await db.transaction(async () => {
        await db.prepare('INSERT INTO customer_sessions (id, owner_id, phone, device, created_at, expires_at, ended_at, ip) VALUES (?, ?, ?, ?, ?, ?, NULL, ?)').run(id, user.id, user.phone, device, stamp(), now() + lifetimeMs, ip)
        await audit(user.id, '登录成功', 'info', { ip, device })
      })
      return token
    },
    async logout(req) {
      const entry = await current(req)
      if (entry) await db.transaction(() => end(entry.id, entry.ownerId, '退出登录', { ip: clientIp(req), device: deviceLabel(req?.headers?.['user-agent']) }))
    },
    async revokeOthers(req) {
      const entry = await current(req)
      if (!entry) return
      await db.transaction(async () => {
        const others = await db.prepare('SELECT id FROM customer_sessions WHERE owner_id = ? AND id <> ? AND ended_at IS NULL FOR UPDATE').all(entry.ownerId, entry.id)
        for (const other of others) await end(other.id, entry.ownerId, '密码修改，会话撤销')
      })
    },
    async failure(user, req) { await audit(user?.id ?? null, '登录失败', 'warn', { ip: clientIp(req), device: deviceLabel(req?.headers?.['user-agent']) }) },
    async phoneChanged(previous, next) { await db.prepare('UPDATE customer_sessions SET phone = ? WHERE phone = ? AND ended_at IS NULL').run(next, previous) },
    async security(req, overview) {
      const entry = requireSession(await current(req))
      const devices = (await db.prepare('SELECT * FROM customer_sessions WHERE owner_id = ? ORDER BY created_at DESC, id DESC').all(entry.ownerId)).map(row => ({
        id: row.id, name: row.device || '未知设备', location: locationText(row.ip), lastActiveAt: row.created_at,
        active: row.ended_at === null && Number(row.expires_at) > now(), current: row.id === entry.id && row.ended_at === null,
      }))
      const logs = (await db.prepare('SELECT * FROM customer_auth_audit WHERE owner_id = ? ORDER BY created_at DESC, seq DESC LIMIT 200').all(entry.ownerId)).map(row => ({
        id: row.id, action: row.action, level: row.level, createdAt: row.created_at,
        detail: ['银行会话审计', locationText(row.ip), row.device].filter(Boolean).join(' · '),
      }))
      return { ...overview, devices, logs, sessionAuditSupported: true }
    },
  }
}
