          const mid = newId('msg')
          await db.prepare('INSERT INTO ticket_messages (id, ticket_id, sender, text, created_at, visible_to_customer) VALUES (?, ?, ?, ?, ?, ?)')
            .run(mid, id, sender, body.text, now(), visibleToCustomer ? 1 : 0)
