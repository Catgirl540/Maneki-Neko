        if (who.role === 'agent') {
          where.push('created_by = ?')
          params.push(who.actorId)
        }
        // 会员 VIP 工单优先，其次加急，同优先级按创建时间倒序
        const page = Number(url.searchParams.get('page') ?? 1), paged = url.searchParams.has('page'), size=Number(url.searchParams.get('size')??100)
