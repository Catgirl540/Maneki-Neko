        const clause = where.length ? 'WHERE ' + where.join(' AND ') : ''
        const sql = `SELECT * FROM tickets ${clause}
          ORDER BY CASE priority WHEN 'vip' THEN 0 WHEN 'high' THEN 1 ELSE 2 END, created_at DESC,id LIMIT ? OFFSET ?`
