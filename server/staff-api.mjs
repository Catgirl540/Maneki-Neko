          await db.prepare('UPDATE tickets SET updated_at = ? WHERE id = ?').run(now(), id)
          await writeAudit({
            actorType: who.actorType,
            actorId: who.actorId,
            action: visibleToCustomer ? 'ticket.message.customer' : 'ticket.message',
            targetType: 'ticket',
            targetId: id,
            reason: visibleToCustomer ? body.text : null,
          })
