import test from 'node:test'
import assert from 'node:assert/strict'
import { fixture, ok, login, register, account, reconcile, testOptions, routes } from './testing/http-fixture.mjs'

test('HTTP applied pending card cannot bypass activation; formal loss recovery preserves status, ownership and funds', { ...testOptions, timeout: 120000 }, async t => {
  const app = await fixture()
  t.after(() => app.close())
  const owner = await register(app, '13900000071', 'TEST ONLY card lifecycle'), other = await login(app, '13600136000')
  ok(await app.call(routes.deposit(owner.accounts[0].id), { method: 'POST', token: owner.token, body: { amount: 100000, channel: 'bank' } }))
  const product = ok(await app.call(routes.cardProducts(), { token: owner.token })).find(row => !row.held)
  const address = { recipient: '卡片测试客户', phone: '13900000071', region: '上海市', city: '上海市', detail: '浦东新区测试路 100 号', postalCode: '200120' }
  const opened = ok(await app.call(routes.cardOpen(), { method: 'POST', token: owner.token, body: { productCode: product.code, address, paymentPassword: '888888' } }))
  const baseline = await account(app, owner)
  const post = (path, body, token = owner.token) => app.call(path, { method: 'POST', token, body })
  const state = async () => ok(await app.call(routes.cards(), { token: owner.token })).find(row => row.id === opened.id)
  assert.equal(opened.status, 'pending')
  assert.equal((await post(routes.cardActivate(opened.id), { paymentPassword: '000000' })).body.code, 'BAD_PAY_PASSWORD')
  for (const locked of [false, true]) assert.equal((await post(routes.cardLock(opened.id), { locked })).body.code, 'CARD_NOT_DELIVERED')
  assert.equal((await post(routes.cardLock(opened.id), { locked: 'false' })).body.code, 'INVALID_CARD_LOCK')
  assert.equal((await app.call(routes.cardSettings(opened.id), { method: 'PATCH', token: owner.token, body: { onlinePayment: true } })).body.code, 'CARD_NOT_DELIVERED')
  assert.equal((await post(routes.cardSpend(opened.id), { platform: 'meituan', amount: 100 })).body.code, 'CARD_NOT_DELIVERED')
  assert.equal((await state()).status, 'pending'); assert.deepEqual(await account(app, owner), baseline)
  assert.equal((await post(routes.cardLost(opened.id), { paymentPassword: '888888' }, other.token)).status, 404)
  const lost = ok(await post(routes.cardLost(opened.id), { paymentPassword: '888888' }))
  assert.equal(lost.status, 'lost'); assert.equal(lost.lostFromStatus, 'pending')
  assert.equal((await post(routes.cardLock(opened.id), { locked: false })).body.code, 'CARD_LOST')
  assert.equal((await post(routes.cardActivate(opened.id), { paymentPassword: '888888' })).body.code, 'CARD_LOST')
  assert.equal((await post(routes.cardSecrets(opened.id), { paymentPassword: '888888' })).body.code, 'CARD_LOST')
  assert.equal((await post(routes.cardSpend(opened.id), { platform: 'meituan', amount: 100 })).body.code, 'CARD_LOST')
  assert.equal((await post(routes.cardOpen(), { productCode: product.code, address, paymentPassword: '888888' })).body.code, 'CARD_NETWORK_LIMIT')
  assert.equal((await post(routes.cardRecover(opened.id), { paymentPassword: '000000' })).body.code, 'BAD_PAY_PASSWORD')
  assert.equal(ok(await post(routes.cardRecover(opened.id), { paymentPassword: '888888' })).status, 'pending')
  assert.deepEqual(await account(app, owner), baseline)
  ok(await post(routes.cardActivate(opened.id), { paymentPassword: '888888' }))
  ok(await app.call(routes.cardSettings(opened.id), { method: 'PATCH', token: owner.token, body: { onlinePayment: true } }))
  const receipt = ok(await post(routes.cardSpend(opened.id), { platform: 'meituan', amount: 100 }))
  assert.equal(receipt.available, baseline.available - 100)
  ok(await post(routes.cardLost(opened.id), { paymentPassword: '888888' }))
  const fresh = ok(await post(routes.cardReplace(opened.id), { address, paymentPassword: '888888' }))
  assert.equal((await state()).status, 'replaced'); assert.equal(fresh.status, 'pending'); assert.equal(fresh.lostFromStatus, null)
  assert.equal((await post(routes.cardRecover(opened.id), { paymentPassword: '888888' })).body.code, 'CARD_NOT_LOST')
  assert.equal((await post(routes.cardLock(fresh.id), { locked: false })).body.code, 'CARD_NOT_DELIVERED')
  assert.equal(ok(await app.call(routes.accounts(), { token: owner.token })).length, 1)
  assert.equal(fresh.accountId, owner.accounts[0].id)
  await reconcile(app)
})
