import { randomUUID } from 'node:crypto'
import { readdirSync, statSync, existsSync, readFileSync, lstatSync } from 'node:fs'
import { join, basename } from 'node:path'

/** PostgreSQL telemetry is separate from immutable financial evidence. */
export async function createOperations({ db, root, backupDir = process.env.BANK_BACKUP_DIR ?? join(root, 'server/data/pg-backups'), probes = [
  { id: 'client', name: '客户端网页', url: process.env.BANK_CLIENT_HEALTH_URL ?? 'http://127.0.0.1:5180/' },
  { id: 'staff', name: '工作人员端网页', url: process.env.BANK_STAFF_HEALTH_URL ?? 'http://127.0.0.1:5180/staff/' },
  { id: 'agent', name: 'AI 服务', url: process.env.BANK_AGENT_HEALTH_URL ?? 'http://127.0.0.1:8788/agent-api/health', json: true, authenticatedHealth: true },
] }) {
  const startedAt = new Date().toISOString()
  if (process.env.BANK_AUTO_MIGRATE !== 'false') await db.exec(`CREATE TABLE IF NOT EXISTS operations_events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, id TEXT PRIMARY KEY, created_at TEXT NOT NULL, level TEXT NOT NULL,
    service TEXT NOT NULL, kind TEXT NOT NULL, status INTEGER, code TEXT NOT NULL)`)
  async function record({ level = 'error', service = 'bank', kind = 'http-error', status = null, code = 'HTTP_ERROR' } = {}) {
    const safeService = ['bank', 'staff', 'settlement'].includes(service) ? service : 'bank'
    const safeKind = ['http-error', 'startup', 'settlement-error'].includes(kind) ? kind : 'http-error'
    const safeCode = ['HTTP_ERROR', 'INTERNAL_ERROR', 'DATABASE_ERROR', 'STARTED', 'SETTLEMENT_FAILED'].includes(code) ? code : 'HTTP_ERROR'
    await db.prepare('INSERT INTO operations_events (id,created_at,level,service,kind,status,code) VALUES (?,?,?,?,?,?,?)').run(randomUUID(), new Date().toISOString(), level === 'info' ? 'info' : 'error', safeService, safeKind, Number.isInteger(status) ? status : null, safeCode)
    await db.exec('DELETE FROM operations_events WHERE id NOT IN (SELECT id FROM operations_events ORDER BY created_at DESC,seq DESC LIMIT 1000)')
  }
  await record({ level: 'info', kind: 'startup', code: 'STARTED' })
  async function probe(item) {
    const start = Date.now()
    try {
      const response = await fetch(item.url, { signal: AbortSignal.timeout(2000), redirect: 'error' })
      if (item.authenticatedHealth && response.status === 401) {
        const body = await response.json()
        return { id: item.id, name: item.name, status: body.code === 'UNAUTHORIZED' ? 'up' : 'down', detail: body.code === 'UNAUTHORIZED' ? '服务可达且启用认证；模型可用性未核实' : '健康认证响应异常', latencyMs: Date.now() - start }
      }
      const healthy = response.ok && (!item.json || (await response.json()).ok === true)
      if (!item.json) await response.body?.cancel()
      return { id: item.id, name: item.name, status: healthy ? 'up' : 'down', detail: healthy ? '服务可访问' : `健康检查失败（HTTP ${response.status}）`, latencyMs: Date.now() - start }
    } catch { return { id: item.id, name: item.name, status: 'down', detail: '无法连接或健康检查超时', latencyMs: Date.now() - start } }
  }
  function backups() {
    if (process.env.BANK_PG_STATUS_FILE) {
      try {
        const statusFile=process.env.BANK_PG_STATUS_FILE, info=lstatSync(statusFile)
        if (!info.isFile() || info.isSymbolicLink() || info.size>8192) throw new Error('Invalid backup status')
        const value=JSON.parse(readFileSync(statusFile,'utf8'))
        if (value.format!=='postgresql-custom' || typeof value.snapshot!=='string' || basename(value.snapshot)!==value.snapshot || !Number.isFinite(Date.parse(value.createdAt)) || !/^[a-f0-9]{64}$/.test(value.sha256) || !Number.isSafeInteger(value.sizeBytes)) throw new Error('Invalid backup status')
        const status=value.status!=='ready'?'invalid':Date.now()-Date.parse(value.createdAt)>2*3600_000?'stale':'ready'
        return {status,detail:status==='ready'?'最近备份工具校验通过；文件与恢复结果须由运维独立复核':'最近备份校验失败或已过期',items:[{name:value.snapshot,createdAt:value.createdAt,sizeBytes:value.sizeBytes,valid:status==='ready'}]}
      } catch { return {status:'missing',detail:'尚无可用的 PostgreSQL 备份状态',items:[]} }
    }
    if (!existsSync(backupDir)) return { status: 'missing', detail: '尚无 PostgreSQL 备份', items: [] }
    const manifests = readdirSync(backupDir).filter(name => name.endsWith('.manifest.json')).map(name => {
      try {
        const file = join(backupDir,name)
        if (lstatSync(file).isSymbolicLink() || statSync(file).size > 65536) return null
        const value = JSON.parse(readFileSync(file,'utf8'))
        if (value.format !== 'postgresql-custom' || value.manifestVersion !== 1 || typeof value.snapshot !== 'string' || basename(value.snapshot) !== value.snapshot || !/^[a-f0-9]{64}$/.test(value.sha256) || !Number.isFinite(Date.parse(value.createdAt))) return null
        const dump = join(backupDir,value.snapshot), info = lstatSync(dump)
        return { name: value.snapshot, sizeBytes: info.size, createdAt: value.createdAt, valid: info.isFile() && !info.isSymbolicLink() && info.size === value.sizeBytes }
      } catch { return null }
    }).filter(Boolean).sort((a,b)=>String(b.createdAt).localeCompare(String(a.createdAt))).slice(0,10)
    const latest=manifests[0], status=!latest?'missing':!latest.valid?'invalid':Date.now()-Date.parse(latest.createdAt)>2*3600_000?'stale':'ready'
    return { status, detail: status==='ready'?'PostgreSQL 备份清单及大小有效；完整哈希与恢复由运维工具校验':'备份缺失、过期或清单异常', items:manifests }
  }
  async function overview() {
    let database, sizeBytes=null
    try {
      const row=await db.prepare('SELECT pg_database_size(current_database()) AS size').get()
      sizeBytes=row.size;database={id:'database',name:'PostgreSQL 数据库',status:'up',detail:'数据库可读取',latencyMs:null}
    } catch { database={id:'database',name:'PostgreSQL 数据库',status:'down',detail:'数据库读取失败',latencyMs:null} }
    const services=[{id:'bank',name:'银行合作平台后端',status:'up',detail:'当前请求由平台后端响应',latencyMs:null},database,...await Promise.all(probes.map(probe))]
    const telemetrySince=(await db.prepare('SELECT MIN(created_at) AS since FROM operations_events').get()).since??startedAt
    return { checkedAt:new Date().toISOString(),startedAt,uptimeSeconds:Math.floor(process.uptime()),services,
      version:{revision:process.env.BANK_RELEASE??null,localChanges:null,node:process.version,environment:process.env.NODE_ENV??'development',telemetrySince},
      database:{sizeBytes,engine:'postgresql'},backups:backups(),
      events:await db.prepare('SELECT id,created_at AS "createdAt",level,service,kind,status,code FROM operations_events ORDER BY created_at DESC,seq DESC LIMIT 100').all(),
      errors24h:(await db.prepare("SELECT COUNT(*) AS n FROM operations_events WHERE level='error' AND created_at>=?").get(new Date(Date.now()-86400000).toISOString())).n }
  }
  return { overview,record }
}
