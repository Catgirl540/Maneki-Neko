#!/usr/bin/env node
/**
 * Create (or reset) the AI-session login role, then print its connection URL.
 *
 * The session store keeps its own least-privilege login (`maneki_ai_session`)
 * on the same PostgreSQL database as the bank. `bootstrap-session-store.mjs`
 * only creates the schema and grants -- it assumes the role already exists --
 * so a local install has an unbridgeable DBA step unless something creates it.
 * That is this file.
 *
 * The owner connection and the new password arrive on stdin, never on the
 * command line: arguments are visible in `ps` to every local user.
 *
 *   echo '{"ownerUrl":"postgres://...","role":"maneki_ai_session","password":"..."}' \
 *     | node tools/create-session-role.mjs
 *
 * Prints one JSON line: { ok, url } or { ok: false, error }.
 */
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(fileURLToPath(new URL('../framework/bridge/pg-runtime/package.json', import.meta.url)))

async function readStdin() {
  const chunks = []
  for await (const chunk of process.stdin) chunks.push(chunk)
  return Buffer.concat(chunks).toString('utf8')
}

/** Only hex/base64url-ish names reach SQL interpolation; everything else is rejected. */
const safeRole = role => /^[a-z_][a-z0-9_]{0,62}$/.test(role)

try {
  const input = JSON.parse(await readStdin())
  const { ownerUrl, role, password } = input ?? {}
  if (!/^postgres(ql)?:\/\//i.test(ownerUrl ?? '')) throw new Error('ownerUrl must be a postgres:// URL')
  if (!safeRole(role)) throw new Error('role name is not a plain identifier')
  // Generated by the launcher as hex, so it needs no quoting and cannot end the string early.
  if (!/^[A-Za-z0-9]{16,128}$/.test(password ?? '')) throw new Error('password must be 16-128 alphanumeric characters')

  const { Client } = require('pg')
  const client = new Client({ connectionString: ownerUrl, application_name: 'maneki-session-role-setup' })
  await client.connect()
  try {
    const database = (await client.query('SELECT current_database() AS name')).rows[0].name
    const exists = (await client.query('SELECT 1 FROM pg_roles WHERE rolname = $1', [role])).rowCount > 0
    // The password is alphanumeric by construction, so embedding it is safe;
    // CREATE/ALTER ROLE cannot take it as a bind parameter.
    if (exists) await client.query(`ALTER ROLE "${role}" LOGIN PASSWORD '${password}'`)
    else await client.query(`CREATE ROLE "${role}" LOGIN PASSWORD '${password}'`)
    // Connect only: no ownership, no schema creation, no access to bank tables.
    await client.query(`GRANT CONNECT ON DATABASE "${database}" TO "${role}"`)

    const url = new URL(ownerUrl)
    url.username = role
    url.password = password
    console.log(JSON.stringify({ ok: true, created: !exists, database, url: url.toString() }))
  } finally {
    await client.end()
  }
} catch (error) {
  console.log(JSON.stringify({ ok: false, error: error?.message ?? String(error) }))
  process.exitCode = 1
}
