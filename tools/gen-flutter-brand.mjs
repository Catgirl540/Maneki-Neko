const pathCode = svg => {
 const tokens = svg.match(/[MLHVZ]|-?\d+(?:\.\d+)?/g); let i=0, x=0, y=0;
 const out=['Path()'];
 while(i<tokens.length) {
   const op=tokens[i++], n=()=>Number(tokens[i++]);
   if(op==='M' || op==='L') {x=n(); y=n(); out.push(`..${op==='M'?'moveTo':'lineTo'}(${x}, ${y})`)}
   else if(op==='H') {x=n(); out.push(`..lineTo(${x}, ${y})`)}
   else if(op==='V') {y=n(); out.push(`..lineTo(${x}, ${y})`)}
   else if(op==='Z')out.push('..close()')
   else throw Error(`Unsupported cat geometry command: ${op}`)
 }
 return out.join('')
}
