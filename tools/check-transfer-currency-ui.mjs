/** 在本地 mock 前端验证首屏付款与收款币种选择。 */
import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { login, gotoInApp } from './lib/session.mjs'

const base = process.argv[2] ?? 'http://127.0.0.1:5180'
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname), '仅限本地 mock')
assert(process.env.CHROME_PATH, '设置 CHROME_PATH 指向 Chromium')
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await page.route('**/agent-api/**', route => route.fulfill({ status: 503, body: '{}' }))
  await login(page, base)
  await gotoInApp(page, '/transfer')
  await page.getByLabel('付款币种', { exact: true }).waitFor()
  const main = page.locator('main')
  const body = await main.innerText()
  assert.match(body, /CNY\s*·\s*人民币/, '单币种也要显示付款账户')
  assert.match(body, /只有人民币余额/, '单币种应提示去换汇')
  assert.equal(await main.getByRole('link', { name: '换汇', exact: true }).getAttribute('href'), '/exchange')
  assert.equal(await main.getByRole('combobox', { name: '付款币种' }).count(), 1)
  assert.equal(await main.getByRole('combobox', { name: '收款币种' }).count(), 1)
  await main.getByText('付款金额', { exact: true }).waitFor()
  const payment = main.getByLabel('转账金额', { exact: true })
  const received = main.getByLabel('收款金额', { exact: true })
  const currency = main.getByLabel('收款币种', { exact: true })
  const waitValue = (label, value) => page.waitForFunction(({ label, value }) =>
    document.querySelector(`input[aria-label="${label}"]`)?.value === value, { label, value })
  await payment.fill('100')
  assert.equal(await received.inputValue(), '100', '同币种收款金额应等于付款金额')
  await currency.selectOption('USD')
  await waitValue('收款金额', '13.93')
  await payment.fill('200')
  assert.notEqual(await received.inputValue(), '13.93', '修改金额后不得展示旧报价')
  await waitValue('收款金额', '27.87')
  await received.fill('10')
  await waitValue('转账金额', '71.76')
  await main.getByText(/参考汇率/).first().waitFor()
  if (process.env.CHECK_QUOTE_EXPIRY === '1') {
    await page.waitForTimeout(32_000)
    await waitValue('转账金额', '71.76')
    await main.getByText(/参考汇率/).first().waitFor()
  }
  await currency.selectOption('CNY')
  assert.equal(await payment.inputValue(), '10.00', '以收款为准切换同币种时付款应同步')
  await currency.selectOption('USD')
  await waitValue('转账金额', '71.76')
  await received.fill('10.123')
  await main.getByRole('button', { name: '下一步', exact: true }).click()
  await main.getByText('请输入有效转账金额，最多两位小数').waitFor()
  await received.fill('10')
  await waitValue('转账金额', '71.76')
  await main.getByText(/参考汇率/).first().waitFor()
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH, fullPage: true })
  await main.getByRole('button', { name: '下一步', exact: true }).click()
  await main.getByText('收款银行', { exact: true }).first().waitFor()
  assert.equal(await main.getByLabel('收款币种', { exact: true }).count(), 0, '收款步骤不应重复显示选择器')
  assert.match(await main.innerText(), /收款币种[\s\S]*美元（USD）/, '收款步骤摘要应保留美元')
  await main.getByLabel('收款账户', { exact: true }).fill('8820000000124471')
  await main.getByLabel('收款人', { exact: true }).fill('陈嘉禾')
  await main.getByRole('button', { name: '下一步', exact: true }).click()
  await main.getByRole('heading', { name: '信息确认', exact: true }).waitFor()
  assert.match(await main.innerText(), /¥71\.76/, '确认页应使用反算后的付款金额')
  assert.match(await main.innerText(), /US\$10\.00/, '确认页应显示报价所得的实际收款金额')
  await main.getByRole('button', { name: '返回修改', exact: true }).click()
  await main.getByRole('button', { name: '上一步', exact: true }).click()
  await main.getByRole('button', { name: /转数快 \/ 跨境支付通/ }).click()
  assert.equal(await currency.locator('option[value="USD"]').count(), 0, '转数快不支持美元')
  await currency.selectOption('CNY')
  assert.equal(await payment.inputValue(), '10.00', '转数快首屏币种选择应更新付款金额')
  await currency.selectOption('HKD')
  await page.waitForFunction(() => {
    const input = document.querySelector('input[aria-label="转账金额"]')
    return input?.value && input.value !== '10.00'
  })
  await main.getByText(/参考汇率/).first().waitFor()
  const rateText = await main.getByText(/参考汇率：1 CNY/).first().innerText()
  const rate = Number(/= ([\d.]+) HKD/.exec(rateText)?.[1])
  assert(rate > 1)
  const missingCent = Array.from({ length: 199 }, (_, i) => i + 1).find(target =>
    !Array.from({ length: 201 }, (_, i) => i + 1).some(source => Math.round(source * rate) === target))
  assert(missingCent, '测试汇率应存在无法精确到账的金额')
  await received.fill((missingCent / 100).toFixed(2))
  await main.getByText(/按当前报价折算，预计实际收款/).waitFor()
  await main.getByRole('button', { name: '下一步', exact: true }).click()
  await main.getByText('收款国家/地区', { exact: true }).waitFor()
  assert.match(await main.innerText(), /收款币种[\s\S]*港币/, '转数快收款步骤应保留首屏选择')

  await gotoInApp(page, '/exchange')
  await page.getByLabel('换汇金额', { exact: true }).fill('100')
  await page.getByRole('button', { name: '获取报价', exact: true }).click()
  await page.getByRole('button', { name: '确认换汇', exact: true }).click()
  const exchange = page.getByRole('dialog', { name: '确认换汇' })
  for (let i = 1; i <= 6; i++) await exchange.getByLabel(`支付密码第 ${i} 位`).fill('8')
  await exchange.getByRole('button', { name: '确认换汇', exact: true }).click()
  await page.getByRole('dialog', { name: '换汇成功' }).getByRole('button', { name: '完成' }).click()
  await gotoInApp(page, '/transfer')
  const payCurrency = main.getByLabel('付款币种', { exact: true })
  await payCurrency.locator('option').filter({ hasText: 'USD' }).waitFor({ state: 'attached' })
  const usd = await payCurrency.locator('option').evaluateAll(options =>
    options.find(option => option.textContent?.includes('USD'))?.value)
  assert(usd, '换汇后应可选择美元余额付款')
  await payCurrency.selectOption(usd)
  assert.equal(await currency.inputValue(), 'CNY', '切换付款币种不应改变默认收款币种')
  await payment.fill('5')
  await page.waitForFunction(() => Boolean(document.querySelector('input[aria-label="收款金额"]')?.value))
  assert.notEqual(await received.inputValue(), '5', '跨币种切换后应按新报价计算收款金额')
  await currency.selectOption('USD')
  assert.equal(await received.inputValue(), '5')
  await payCurrency.selectOption({ label: 'CNY · 人民币' })
  assert.equal(await currency.inputValue(), 'USD', '切换付款币种不应改变已选美元收款币种')
  await page.waitForFunction(() => Boolean(document.querySelector('input[aria-label="收款金额"]')?.value))
  assert.notEqual(await received.inputValue(), '5', '切换付款币种后应重新报价')
  await payCurrency.selectOption(usd)
  assert.equal(await currency.inputValue(), 'USD', '付款与收款相同时不应重置收款币种')
  await currency.selectOption('CNY')
  await payCurrency.selectOption({ label: 'CNY · 人民币' })
  assert.equal(await currency.inputValue(), 'CNY', '切换为相同币种时收款币种保持一致')
  await payCurrency.selectOption(usd)
  assert.equal(await currency.inputValue(), 'CNY', '付款币种再次切换时收款币种仍保持人民币')
  assert.deepEqual(errors, [])
  console.log('PASS 付款金额、预计收款金额、币种切换、报价更新及转数快')
} finally {
  await browser.close()
}
