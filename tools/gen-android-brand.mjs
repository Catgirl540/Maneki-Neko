/** Reuse the web brand geometry for Android vector/adaptive icons. Node 24+. */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { CAT_MARK as cat, CAT_MARK_GOLD } from '../app/src/components/brand/cat-mark.ts'
const root = fileURLToPath(new URL('../android/app/src/main/res/', import.meta.url))
const circle = (cx, cy, rx, ry = rx) => `M${cx-rx},${cy} a${rx},${ry} 0,1 0,${rx*2},0 a${rx},${ry} 0,1 0,-${rx*2},0 Z`
const shape = [circle(cat.head.cx,cat.head.cy,cat.head.r), ...cat.eyes.map(e=>circle(e.cx,e.cy,e.rx,e.ry)), cat.nose].join(' ')
const paths = color => `<path android:fillColor="${color}" android:pathData="${cat.ears.join(' ')}" />
    <path android:fillColor="${color}" android:fillType="evenOdd" android:pathData="${shape}" />
    <path android:fillColor="#00000000" android:strokeColor="${color}" android:strokeWidth="${cat.whiskerWidth}" android:strokeLineCap="round" android:pathData="${cat.whiskers.join(' ')}" />`
const vector = (size, viewport, content) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-android-brand.mjs from cat-mark.ts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
    ${content}
</vector>
`
const adaptive = monochrome => `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_background" />
    <foreground android:drawable="@drawable/launcher_foreground" />${monochrome ? '\n    <monochrome android:drawable="@drawable/launcher_monochrome" />' : ''}
</adaptive-icon>
`
const files = {
  'drawable/brand_cat.xml': vector(64,64,paths(CAT_MARK_GOLD)),
  'drawable/launcher_foreground.xml': vector(108,108,`<group android:scaleX="0.9" android:scaleY="0.9" android:translateX="25.2" android:translateY="23">${paths(CAT_MARK_GOLD)}</group>`),
  'drawable/launcher_monochrome.xml': vector(108,108,`<group android:scaleX="0.9" android:scaleY="0.9" android:translateX="25.2" android:translateY="23">${paths('#FF000000')}</group>`),
  'values/launcher_colors.xml': '<?xml version="1.0" encoding="utf-8"?>\n<resources><color name="launcher_background">#F7F5F0</color></resources>\n',
}
for (const version of [26,33]) for (const name of ['ic_launcher','ic_launcher_round']) files[`mipmap-anydpi-v${version}/${name}.xml`] = adaptive(version === 33)
for (const [path, content] of Object.entries(files)) {
  if (process.argv.includes('--check')) {
    if (await readFile(root+path,'utf8').catch(()=>null) !== content) throw Error(`Android brand asset is stale: ${path}`)
  } else { await mkdir(root+path.substring(0,path.lastIndexOf('/')), {recursive:true}); await writeFile(root+path,content) }
}
console.log(`PASS Android brand: ${Object.keys(files).length} assets ${process.argv.includes('--check') ? 'verified' : 'generated'}`)
