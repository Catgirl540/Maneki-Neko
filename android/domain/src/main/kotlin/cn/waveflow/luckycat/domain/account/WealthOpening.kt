package cn.waveflow.luckycat.domain.account

/**
 * 开立**理财账户**。
 *
 * ## 银行账户 ≠ 理财账户（和 ZA 一样的分法）
 *
 * 银行账户是装钱的地方，理财账户才是买理财的资格。理财账户不装钱，
 * 它把「你」和理财公司之间的委托关系立起来，申购扣款与赎回到账都走
 * 用户指定的那个资金账户。
 *
 * ## 前置条件，一个都不能少
 *
 * 1. **风险承受能力评估**——监管要求，而且**满一年就失效**（过期等同于没做）。
 *    没有它后端回 403 `RISK_ASSESSMENT_REQUIRED`。界面在测评做完之前
 *    就该把"开立"按钮置灰，而不是让用户填完一整套再被拒。
 * 2. 实名核验：姓名 + 身份证 + 短信 + 人脸票据。
 * 3. 签署投资协议（**逐字校验**）+ 指定资金账户。
 */
object WealthOpening {

    /**
     * 投资协议文本。**逐字**抄自网页版 `lib/wealth.ts` 的
     * `WEALTH_INVESTMENT_AGREEMENT`，后端也是逐字比对
     * （`req.agreement.trim() !== WEALTH_INVESTMENT_AGREEMENT` 就拒）。
     */
    const val AGREEMENT =
        "本人已阅读并同意《理财产品投资协议》《风险揭示书》及《投资者权益须知》，自愿开立理财账户并独立承担投资风险"

    /** 开理财账户要做三件事，界面上按这个顺序讲给用户。 */
    val STEPS = listOf(
        "风险承受能力评估" to "监管要求，结果有效期一年",
        "实名身份核验" to "姓名 / 身份证 / 短信 / 人脸",
        "签署投资协议" to "并指定一个资金账户",
    )
}
