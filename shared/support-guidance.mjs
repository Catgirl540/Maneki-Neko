export function supportGuidance(input) {
  const rule = rules.find(row => row.match.test(typeof input === 'string' ? input : ''))
  return {
    text: '当前为固定引导，未实时查询账户或执行业务。' + (rule?.text ?? '请打开对应银行页面查看实际数据，或待助手服务恢复后继续；需要人工帮助可在助手页提交工单。'),
    actions: [{ label: rule?.label ?? '查看助手服务', to: rule?.to ?? '/support' }],
  }
}
